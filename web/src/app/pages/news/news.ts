import { Component, OnDestroy, OnInit, computed, inject, signal } from '@angular/core';
import { DatePipe } from '@angular/common';
import { SchoolService } from '../../features/schools/school.service';
import { SchoolNews } from '../../features/schools/school.model';
import { FavoritesService } from '../../shared/favorites.service';
import { AuthService } from '../../features/auth/auth.service';
import { RouterLink } from '@angular/router';
import { Subscription } from 'rxjs';

@Component({
  selector: 'app-news',
  imports: [DatePipe, RouterLink],
  templateUrl: './news.html',
  styleUrl: './news.css',
})
export class News implements OnInit, OnDestroy {
  private readonly schools = inject(SchoolService);
  protected readonly auth = inject(AuthService);
  protected readonly favorites = inject(FavoritesService);
  readonly items = signal<SchoolNews[]>([]);
  readonly query = signal('');
  readonly favoritesOnly = signal(false);
  readonly page = signal(0);
  readonly totalPages = signal(0);
  readonly loading = signal(false);
  readonly error = signal('');
  private searchTimer?: ReturnType<typeof setTimeout>;
  private request?: Subscription;
  readonly articleImages = signal<Record<number, string>>({});
  readonly filteredItems = computed(() => {
    const query = this.query().trim().toLowerCase();
    return this.items().filter(
      (item) =>
        (!query ||
          [item.title, item.schoolName, item.content].some((value) =>
            value.toLowerCase().includes(query),
          )) &&
        (!this.favoritesOnly() || this.favorites.has('article', item.id)),
    );
  });
  ngOnInit() {
    this.load(0);
  }

  ngOnDestroy(): void {
    clearTimeout(this.searchTimer);
    this.request?.unsubscribe();
  }

  private imageFromContent(content: string): string | null {
    // Only use relative image URLs generated by Barkly; do not parse or load remote media.
    const image = content.match(
      /<img\b[^>]*?\bsrc\s*=\s*["'](\/api\/training-images\/[a-z0-9_-]+\.(?:jpg|jpeg|png|webp))["']/i,
    );
    return image?.[1] ?? null;
  }

  search(query: string): void {
    this.query.set(query);
    clearTimeout(this.searchTimer);
    this.searchTimer = setTimeout(() => this.load(0), 250);
  }

  excerpt(content: string): string {
    const text = content
      .replace(/<[^>]*>/g, ' ')
      .replace(/&nbsp;/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    return text.length > 190 ? `${text.slice(0, 187).trimEnd()}…` : text;
  }

  loadMore(): void {
    if (this.loading()) return;
    this.load(this.page() + 1, true);
  }

  toggleFavorites(): void {
    if (!this.auth.currentUser()) return;
    this.favoritesOnly.set(!this.favoritesOnly());
    this.load(0);
  }

  retry(): void {
    this.load(0);
  }

  private load(page: number, append = false): void {
    this.loading.set(true);
    this.error.set('');
    this.request?.unsubscribe();
    this.request = this.schools
      .searchNews$(this.query(), page, 20, this.favoritesOnly())
      .subscribe({
        next: (result) => {
          const images = append ? { ...this.articleImages() } : {};
          for (const article of result.items) {
            const image = this.imageFromContent(article.content);
            if (image) images[article.id] = image;
          }
          this.articleImages.set(images);
          this.items.set(append ? [...this.items(), ...result.items] : result.items);
          this.page.set(result.page);
          this.totalPages.set(result.totalPages);
          this.loading.set(false);
        },
        error: () => {
          this.loading.set(false);
          this.error.set('Nie udało się pobrać artykułów.');
        },
      });
  }
}
